import fs from 'node:fs';
import path from 'node:path';
import { launch, Page, profileDir, artifactsDir, sleep } from './lib/cdp.mjs';
const PORT=9336;
const URL='https://x.com/PeanutPair/status/2121936197966819729';
await launch({port:PORT,profile:profileDir('x'),startUrl:URL,proxy:process.env.X_PROXY});
const p=await Page.attach(PORT);
await p.goto(URL);
await sleep(7000);
const texts=await p.eval("(()=>[...document.querySelectorAll('[data-testid=\"tweetText\"]')].map(e=>e.innerText.replace(/\\s+/g,' ').slice(0,26)))()");
const shot=await p.screenshot(path.join(artifactsDir('x'),'thread-state.png'));
console.log(JSON.stringify({count:texts.length,texts,shot},null,2));
process.exit(0);
